def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo-root", type=Path,
                    default=Path(__file__).resolve().parent.parent,
                    help="repo root containing results/ (default: this repo)")
    ap.add_argument("--out", default="docs/PAPER_TABLES.md",
                    help="output markdown path, relative to repo root")
    ap.add_argument("--no-tex", action="store_true",
                    help="skip the LaTeX companion file (<out>.tex)")
    ap.add_argument("--no-check", action="store_true",
                    help="skip sanity checks against known best-stream values")
    args = ap.parse_args()
    repo = args.repo_root

    # ---- gather rows -------------------------------------------------------
    t1_rows: List[Dict] = []
    t2_rows: List[Dict] = []

    for label, amota, amotp, samota, mota, src in PUBLISHED_ROWS:
        t1_rows.append({"label": label, "source": src,
                        "metrics": {"amota": amota, "amotp": amotp,
                                    "samota": samota, "mota": mota,
                                    "hota": None, "ids": None}})

    for label, rel_path, key, ours_path in ANCHOR_REPLICATIONS:
        r = load_stream(repo, rel_path, key)
        src = f"`{rel_path}` (key `{key}`)"
        if ours_path is not None:
            r2 = load_stream(repo, ours_path, key)
            # Same tracks: the V2V-protocol number must agree across copies.
            if abs(r2["v2v4real_amota_mean"] - r["v2v4real_amota_mean"]) > 1e-6:
                print(f"WARNING: {label!r}: Table-1/Table-2 source summaries "
                      f"disagree on V2V AMOTA", file=sys.stderr)
            src2 = f"`{ours_path}` (key `{key}`)"
            src1 = f"{src}; HOTA/IDS from same-tracks re-score {src2}"
            t1_rows.append({"label": label, "source": src1,
                            "metrics": _v2v_row(r, r_ours=r2)})
            t2_rows.append({"label": label, "source": src2,
                            "metrics": _ours_row(r2)})
        else:
            t1_rows.append({"label": label, "source": src,
                            "metrics": _v2v_row(r)})
            t2_rows.append({"label": label, "source": src,
                            "metrics": _ours_row(r)})

    for short_id, label, rel_path in SWEEP_CONFIGS:
        r = load_stream(repo, rel_path, BEST_STREAM_KEY)
        src = f"`{rel_path}` (key `{BEST_STREAM_KEY}`)"
        t1_rows.append({"label": label, "source": src, "metrics": _v2v_row(r)})
        t2_rows.append({"label": label, "source": src, "metrics": _ours_row(r)})
        if not args.no_check:
            exp_v2v, exp_ours = EXPECTED_BEST[short_id]
            got_v2v = r["v2v4real_amota_mean"]
            got_ours = r["paper_amota_mean"]
            if abs(got_v2v - exp_v2v) > 0.05 or abs(got_ours - exp_ours) > 0.05:
                print(f"SANITY FAIL {short_id}: expected V2V/Ours "
                      f"{exp_v2v}/{exp_ours}, got {got_v2v:.2f}/{got_ours:.2f}",
                      file=sys.stderr)
                return 2

    for short_id, label, rel_path in MH1MA5_SWEEP_CONFIGS:
        r = load_stream(repo, rel_path, BEST_STREAM_KEY)
        src = f"`{rel_path}` (key `{BEST_STREAM_KEY}`)"
        t1_rows.append({"label": label, "source": src, "metrics": _v2v_row(r)})
        t2_rows.append({"label": label, "source": src, "metrics": _ours_row(r)})
        if not args.no_check:
            exp_v2v, exp_ours = EXPECTED_MH1MA5[short_id]
            got_v2v = r["v2v4real_amota_mean"]
            got_ours = r["paper_amota_mean"]
            if abs(got_v2v - exp_v2v) > 0.05 or abs(got_ours - exp_ours) > 0.05:
                print(f"SANITY FAIL {short_id}: expected V2V/Ours "
                      f"{exp_v2v}/{exp_ours}, got {got_v2v:.2f}/{got_ours:.2f}",
                      file=sys.stderr)
                return 2

    for short_id, label, rel_path in MH1MA5_BASELINE_ROWS:
        if not (repo / rel_path).is_file():
            print(f"[skip] {short_id}: re-score summary not yet at {rel_path} "
                  f"(row omitted until the mh1ma5_rescore_* configs run)",
                  file=sys.stderr)
            continue
        r = load_stream(repo, rel_path, ANCHOR_KEY)
        src = (f"`{rel_path}` (key `{ANCHOR_KEY}`); DMSTrack-exact protocol "
               "re-score; V2V cross-checked against "
               "`results/paper_metrics_mh1ma5_matrix.md`")
        t1_rows.append({"label": label, "source": src, "metrics": _v2v_row(r)})
        t2_rows.append({"label": label, "source": src, "metrics": _ours_row(r)})
        if not args.no_check:
            exp_v2v = EXPECTED_MH1MA5_BASELINE[short_id]
            got_v2v = r["v2v4real_amota_mean"]
            if abs(got_v2v - exp_v2v) > 0.1:
                print(f"SANITY FAIL {short_id}: expected V2V AMOTA "
                      f"{exp_v2v}, got {got_v2v:.2f}", file=sys.stderr)
                return 2

    for short_id, label, rel_path in S3_ROWS:
        r = load_stream(repo, rel_path, ANCHOR_KEY)
        src = (f"`{rel_path}` (key `{ANCHOR_KEY}`); DMSTrack-exact protocol "
               "re-score of the S3 KITTI dumps — V2V AMOTA cross-checked "
               "against `results/paper_metrics_V2V_noinject.md` / "
               "`results/paper_metrics_S3NoNorm_sabre_quad.md`")
        t1_rows.append({"label": label, "source": src, "metrics": _v2v_row(r)})
        t2_rows.append({"label": label, "source": src, "metrics": _ours_row(r)})
        if not args.no_check:
            exp_v2v = EXPECTED_S3[short_id]
            got_v2v = r["v2v4real_amota_mean"]
            if abs(got_v2v - exp_v2v) > 0.1:
                print(f"SANITY FAIL {short_id}: expected V2V AMOTA "
                      f"{exp_v2v}, got {got_v2v:.2f}", file=sys.stderr)
                return 2

    if not args.no_check:
        for row in t1_rows:
            exp = EXPECTED_ANCHORS.get(row["label"])
            if exp is not None and abs(row["metrics"]["amota"] - exp) > 0.05:
                print(f"SANITY FAIL anchor {row['label']!r}: expected AMOTA "
                      f"{exp}, got {row['metrics']['amota']:.2f}", file=sys.stderr)
                return 2

    # ---- render ------------------------------------------------------------
    fnotes = FootnoteBank()
    parts = [
        "# Paper result tables (auto-generated)",
        "",
        "Generated by `scripts/paper_protocol_tables.py` from precomputed "
        "summary JSONs — no tracker re-runs. Regenerate with:",
        "",
        "```bash",
        "python scripts/paper_protocol_tables.py",
        "```",
        "",
        "Protocol definitions and evaluator provenance: "
        "`results/EVAL_PROTOCOLS_AND_FIXES.md` (our scorer is bit-identical "
        "to the cleaned DMSTrack `evaluate.py` at 1.1e-16; the V2V column "
        "preserves the published FP-ignore behavior).",
        "",
        render_table1(t1_rows, fnotes),
        "",
        render_table2(t2_rows, fnotes),
        "",
        render_appendix(repo, fnotes),
        "",
        "## Sources",
        "",
        fnotes.render(),
        "",
    ]
    out_path = repo / args.out
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(parts))
    print(f"wrote {out_path}")

    if not args.no_tex:
        tex_path = out_path.with_suffix(".tex")
        tex_path.write_text(render_tex(t1_rows, t2_rows))
        print(f"wrote {tex_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
