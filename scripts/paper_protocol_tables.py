class FootnoteBank:
    """Auto-numbered footnotes; identical sources share one number."""

    def __init__(self) -> None:
        self._notes: List[str] = []

    def ref(self, text: str) -> str:
        if text not in self._notes:
            self._notes.append(text)
        return f"[^{self._notes.index(text) + 1}]"

    def render(self) -> str:
        return "\n".join(f"[^{i + 1}]: {t}" for i, t in enumerate(self._notes))


