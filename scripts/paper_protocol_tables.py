def render_appendix(repo: Path, fnotes: FootnoteBank) -> str:
    parts = [
        "## Appendix — full filter × covariance ablation (30 streams per config)",
        "",
        "Per sweep config: every filter family (EKF, CI, AKF, PF, BICI, SABRE) "
        "× covariance mode (baseline, static, GPEM-linear/-quadratic/-polar). "
        "AMOTA / AMOTP / MOTA are reported under both protocols: V2V "
        "(DMSTrack, FP-ignore) and Ours (FP-counted, merged GT). HOTA is the "
        "single FP-counted value (computed against per-vehicle GT pending "
        "merged-GT re-score; no FP-ignore HOTA is defined). IDS comes from "
        "the Ours evaluation and is protocol-invariant "
        "(`results/EVAL_PROTOCOLS_AND_FIXES.md` §4). Lower is better for "
        "AMOTP and IDS. Best value per column in **bold**.",
        "",
    ]
    for short_id, label, rel_path in SWEEP_CONFIGS:
        with open(repo / rel_path) as f:
            results = json.load(f)["results"]
        ref = fnotes.ref(f"`{rel_path}`")
        title = label.replace("Ours (SABRE + GPEM-polar) — ", "")
        parts.append(f"### {title}{ref}")
        parts.append("")
        rows = []
        for filt in FILTERS:
            for cov_label, cov_key in COVS:
                key = _stream_key(filt, cov_key)
                r = results.get(key)
                if r is None:
                    rows.append((filt, cov_label, None))
                    continue
                rows.append((filt, cov_label, {
                    "amota_v2v":  r.get("v2v4real_amota_mean"),
                    "amota_ours": r.get("paper_amota_mean"),
                    "amotp_v2v":  r.get("v2v4real_amotp_mean"),
                    "amotp_ours": r.get("paper_amotp_mean"),
                    "mota_v2v":   r.get("v2v4real_mota_mean"),
                    "mota_ours":  r.get("paper_mota_mean"),
                    "hota":       r.get("hota_mean"),
                    "ids":        r.get("paper_ids_total"),
                }))
        # column-wise best for bolding (AMOTP and IDS: lower is better)
        _COLS = ("amota_v2v", "amota_ours", "amotp_v2v", "amotp_ours",
                 "mota_v2v", "mota_ours", "hota", "ids")
        _LOWER_IS_BETTER = {"amotp_v2v", "amotp_ours", "ids"}
        best = {}
        for col in _COLS:
            vals = [m[col] for _, _, m in rows if m and m[col] is not None]
            if not vals:
                best[col] = None
            else:
                best[col] = min(vals) if col in _LOWER_IS_BETTER else max(vals)
        parts.append(
            "| Filter | Covariance "
            "| AMOTA V2V | AMOTA Ours | AMOTP V2V | AMOTP Ours "
            "| MOTA V2V | MOTA Ours | HOTA | IDS |")
        parts.append("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|")
        for filt, cov_label, m in rows:
            if m is None:
                parts.append(f"| {filt} | {cov_label} |" + " — |" * len(_COLS))
                continue
            cells = []
            for col in _COLS:
                s = (f"{m[col]:d}" if col == "ids" and m[col] is not None
                     else fv(m[col]))
                if m[col] is not None and best[col] is not None and \
                        abs(m[col] - best[col]) < 1e-9:
                    s = f"**{s}**"
                cells.append(s)
            parts.append(f"| {filt} | {cov_label} | " + " | ".join(cells) + " |")
        parts.append("")
    return "\n".join(parts)


# ---------------------------------------------------------------------------
# LaTeX (booktabs) for the two headline tables
# ---------------------------------------------------------------------------

def _tex_escape(s: str) -> str:
    # Row labels already escape underscores; handle the rest minimally.
    return (s.replace("&", "\\&").replace("%", "\\%")
             .replace(">=", "$\\geq$").replace("≥", "$\\geq$")
             .replace("—", "--").replace("×", "$\\times$"))


def render_tex(t1_rows: List[Dict], t2_rows: List[Dict]) -> str:
    L: List[str] = [
        "% Auto-generated by scripts/paper_protocol_tables.py — do not edit.",
        "% Sources for every row: see docs/PAPER_TABLES.md footnotes.",
        "",
        "\\begin{table*}[t]\\centering",
        "\\caption{V2V protocol (DMSTrack-comparable, FP-ignore). HOTA and"
        " IDS are sourced from the FP-counted evaluation of the same tracks"
        " (FP treatment moves DetA only; IDS is invariant to FP treatment)."
        " Published rows report neither.}",
        "\\label{tab:v2v_protocol}",
        "\\begin{tabular}{@{}lrrrrrr@{}}",
        "\\toprule",
        "Method & AMOTA$\\uparrow$ & AMOTP$\\uparrow$ & sAMOTA$\\uparrow$ & "
        "MOTA$\\uparrow$ & HOTA$\\uparrow$ & IDS$\\downarrow$ \\\\ \\midrule",
    ]
    for row in t1_rows:
        m = row["metrics"]
        cells = [_tex_escape(row["label"]), fv(m["amota"]), fv(m["amotp"]),
                 fv(m["samota"]), fv(m["mota"]), fv(m.get("hota")),
                 fi(m.get("ids"))]
        L.append(" & ".join(c.replace("—", "--") for c in cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]

    L += [
        "\\begin{table*}[t]\\centering",
        "\\caption{Ours protocol: FP-counted, with the cross-CAV dual-GT "
        "overlap spatially deduplicated (merged GT). Sweep-config HOTA is "
        "computed against per-vehicle GT pending merged-GT re-score.}",
        "\\label{tab:ours_protocol}",
        "\\begin{tabular}{@{}lrrrrrr@{}}",
        "\\toprule",
        "Method & AMOTA$\\uparrow$ & AMOTP$\\uparrow$ & sAMOTA$\\uparrow$ & "
        "MOTA$\\uparrow$ & HOTA$\\uparrow$ & IDS$\\downarrow$ \\\\ \\midrule",
    ]
    for row in t2_rows:
        m = row["metrics"]
        cells = [_tex_escape(row["label"]),
                 fv(m["amota"]), fv(m["amotp"]),
                 fv(m["samota"]), fv(m["mota"]),
                 fv(m["hota"]), fi(m["ids"])]
        L.append(" & ".join(c.replace("—", "--") for c in cells) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    return "\n".join(L)


