                                  # leave headroom but both produce identical
                                  # assignments because they only flag infeasible
                                  # cells; their absolute magnitude is irrelevant.


# ─── KITTI-inherited ignore filters (evaluate.py defaults) ────────────────────
# For V2V4Real, GT carries all flags = 0 and 2D bbox = 0, so these filters
# only fire on TRACKER rows (via min_height on the all-zero 2D box) — that is
# the documented FP-ignore mechanism in protocol='v2v'. See evaluate.py.
KITTI_MAX_TRUNCATION = 0
