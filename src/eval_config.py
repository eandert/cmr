# AB3DMOT_ROOT is a symlink into a DMSTrack monorepo, the DMSTrack package
# lives at `<symlink target>/.. / DMSTrack`. The runner needs both that
# directory AND its parent on PYTHONPATH so `from DMSTrack.model import …`
# resolves. Derive these from the resolved symlink so no workstation string
# literal appears in cmr code.
_AB3DMOT_RESOLVED_PARENT = AB3DMOT_ROOT.resolve().parent
