# ─── Paths ────────────────────────────────────────────────────────────────────

# AB3DMOT is vendored under cmr/third_party/AB3DMOT/. In the published cmr
# this is a pinned git submodule; until then it's a symlink to the workstation
# clone. Either way, no cmr code should ever reach outside cmr to find it.
# If you're a developer needing a different AB3DMOT, point the symlink (or
# submodule) at your fork — do NOT add a workstation-path fallback here.
